# List
car = [1,4,9,8,3]
print (car)

# list with different data types
house = [3,"house",6.8,False] 
print (house)

# list indexing
box = ["ball","toy","blocks"]
print (box[0])
print (box[1])
print (box[2])

# updating list elements
chest = ["gold","silver","diamond"]
chest [0]="key"
print (chest)

# append
num = [3, 9, 0, 1]
num.append(3)
print (num)

# insert
xylophone = [2, 4, 5]
xylophone.insert(4,3)
print (xylophone)

# extend
a = [1,2]
b = [3,4]
a.extend(b)
print (a)

# removing elements
Blasphemous = [3, 7, 8]
Blasphemous.remove(7)
print (Blasphemous)

# pop
s = [34, 78, 21]
s.pop()
print (s)

# del
d = [1,2,3,4]
del d[2]
print (d)

# clear
c = [1,2,3]
c.clear(1)
print (c)