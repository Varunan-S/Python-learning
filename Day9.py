# String strip
text = "   python   "
print (text.strip())

# lsstrip
t = "   python"
print  (text.lstrip())

# rstrip
txt = "python   "
print (txt.rstrip())

# Replace
S = "I like Wanda"
print (S.replace("Wanda", "Spiderman"))

# Split 
k = "I love you"
print (k.split())

# Join
alpha = ["B", "A", "T"]
print ("-".join(alpha))

# find keyword
word = "youth"
print (word.find("u"))

# Index keyword
word = "Python"
print (word.index("o"))

# Count keyword
wn = "cheese"
print (wn.count("e"))

# Start keyword
Z = "banana" 
print (Z.startswith("ban")) 