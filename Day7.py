# For Loop
for i in range (1,9):
    print (i)

for i in range (5):
    print ("TCS")

# While Loop
count = 1
while count <= 5:
    print (count)
    count += 1

# Looping with String
name = "Baasha"
for i in name:
    print (i)

# Example
count = 2
while count <= 20:
    if count % 2 == 0:
        print (count)
    count += 1

# Break Statement
for i in range (1,8):
    if i == 5:
        break
    print (i)

# Continue Statement
for i in range (1,74):
    if i == 34:
        continue 
    print (i)